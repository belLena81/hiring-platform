package com.example.graphQL.cats.api.http

import cats.effect.{IO, IOApp}
import com.example.graphQL.cats.api.admission.PersistedQueryPolicy
import java.nio.charset.StandardCharsets
import java.nio.file.{Files, Path}
import scala.jdk.CollectionConverters.*

/** Generates the persisted-query manifest from the operation fixtures. This is the single place to regenerate it:
  * `sbt "Test / runMain com.example.graphQL.cats.api.http.PersistedQueryManifestCapture"`. The schema snapshot and the
  * introspection fixture are not application operations and are not listed.
  */
object PersistedQueryManifestCapture extends IOApp.Simple {
  val FixtureDirectory: Path = Path.of("src/test/resources/graphql")
  val ManifestPath: Path = FixtureDirectory.resolve("persisted-queries.manifest")
  private val Excluded = Set("hiring.graphql", "introspection.graphql")

  def operationFixtures(directory: Path): List[Path] = {
    val listing = Files.list(directory)
    try
      listing
        .iterator()
        .asScala
        .toList
        .filter { path =>
          val name = path.getFileName.toString
          name.endsWith(".graphql") && !Excluded.contains(name)
        }
        .sortBy(_.getFileName.toString)
    finally listing.close()
  }

  def manifestText(directory: Path): String =
    operationFixtures(directory)
      .map { path =>
        val query = Files.readString(path, StandardCharsets.UTF_8)
        s"# ${path.getFileName}\n${PersistedQueryPolicy.hash(query)}\n"
      }
      .mkString("# Generated by PersistedQueryManifestCapture from the operation fixtures; do not edit.\n", "", "")

  def run: IO[Unit] =
    IO.blocking(Files.writeString(ManifestPath, manifestText(FixtureDirectory), StandardCharsets.UTF_8)).void
}
